const permissionsById = new Map(
  permissionDefinitions.map((permission) => [permission.id, permission]),
);

function getPermission(permissionId) {
  return permissionsById.get(permissionId);
}

function hasPermission(permissionId) {
  return permissionsById.has(permissionId);
}

function listPermissions() {
  return permissionDefinitions.map((permission) => ({ ...permission }));
}

function getPermissionRegistry() {
  return {
    id: PERMISSION_REGISTRY_ID,
    name: `Permission Registry v${PERMISSION_REGISTRY_VERSION}`,
    version: PERMISSION_REGISTRY_VERSION,
    permissions: listPermissions(),
  };
}

