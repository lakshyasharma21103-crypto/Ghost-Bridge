function caller(request) { return { partner: request.partner, requestId: request.requestId, traceId: request.traceId, authorization: request.authorization }; }
function input(request, extra = {}) { return { ...request.query, ...request.body, ...extra, idempotencyKey: request.get('Idempotency-Key') || request.body?.idempotencyKey }; }
function handler(operation, statusCode = 200) { return async (request, response, next) => { try { response.status(statusCode).json({ success: true, data: await operation(request) }); } catch (error) { next(error); } }; }

